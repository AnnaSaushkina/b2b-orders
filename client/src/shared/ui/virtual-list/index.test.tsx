import { describe, it } from 'vitest';

/**
 * Описания кейсов — тела пустые, ассерты пишет Аня (жёлтая зона).
 *
 * Ловушка jsdom, прочитать до первого ассерта:
 * в jsdom нет layout-движка. `getBoundingClientRect()` и `offsetHeight` всегда
 * возвращают нули, поэтому виртуализатор считает, что окно нулевой высоты, и
 * не отдаёт ни одного элемента. Чтобы тесты вообще что-то увидели, размеры
 * скролл-контейнера придётся подменить вручную (замокать `getBoundingClientRect`
 * на прототипе `HTMLElement` в `beforeEach`).
 * Это первое, что нужно решить — без этого зелёными будут только кейсы про пустой список.
 */
describe('VirtualList', () => {
  describe('рендер окна', () => {
    it('рендерит только элементы видимого окна, а не весь items');

    it('число отрендеренных узлов не растёт при увеличении items с 200 до 50 000');

    it('распорка имеет высоту всего списка, а не только видимой части');

    it('каждый элемент спозиционирован абсолютно по своему virtualItem.start');
  });

  describe('контракт', () => {
    it('передаёт в renderItem сам товар, а не virtualItem');

    it('работает с любым типом, у которого есть id (дженерик)');

    it('использует id товара как key, а не индекс массива');
  });

  describe('граничные случаи', () => {
    it('на пустом items не падает и не рендерит ни одного элемента');

    it('не падает, если items короче, чем count внутри виртуализатора');
  });

  describe('пагинация', () => {
    it('вызывает onEndReached, когда последний видимый элемент — последний в items');

    it('не вызывает onEndReached, пока до конца списка не доскроллили');

    it('не вызывает onEndReached повторно, пока последний видимый индекс не изменился');

    it('не падает, если onEndReached не передан (проп опциональный)');
  });

  describe('динамическая высота', () => {
    it('после замера реальной высоты элементы не накладываются друг на друга');

    it('общая высота списка пересчитывается после замера узлов');
  });
});
